/* "2026-11-14 22:05" → "2026.11.14 (토) 22:05" */
const WD = ["일", "월", "화", "수", "목", "금", "토"];
export function formatAt(at: string) {
  const [d, t] = at.split(" ");
  const [y, m, day] = d.split("-").map(Number);
  const wd = WD[new Date(Date.UTC(y, m - 1, day)).getUTCDay()];
  return `${d.replaceAll("-", ".")} (${wd}) ${t}`;
}
