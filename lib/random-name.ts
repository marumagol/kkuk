/* 처음 로그인할 때 미리 채워 주는 이름 : 꾸밈말 + 동물 (예 : 까만 고양이). 2026-11-18 마루님 요청 */
const ADJ = ["까만", "하얀", "노란", "말랑한", "졸린", "배고픈", "신난", "느긋한", "용감한", "수줍은", "포근한", "반짝이는", "호기심 많은", "길 잃은", "부지런한", "엉뚱한", "씩씩한", "몽글몽글한", "떠나는", "설레는"];
const ANIMAL = ["고양이", "강아지", "토끼", "펭귄", "수달", "다람쥐", "판다", "여우", "부엉이", "고래", "햄스터", "코알라", "알파카", "거북이", "오리", "곰", "물개", "고슴도치", "너구리", "참새"];

const pick = <T,>(a: T[]) => a[Math.floor(Math.random() * a.length)];

export function randomName(except?: string) {
  for (;;) {
    const n = `${pick(ADJ)} ${pick(ANIMAL)}`;
    if (n !== except) return n;
  }
}
